import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { renderCodeEmail } from "../api/_lib/email-content.js";
import { SUPPORTED_LOCALES, escapeHtml } from "../api/_lib/security.js";

// Usage:
//   node scripts/render-code-email-preview.js <output-dir>    every language: email-<locale>.html + index.html
//   node scripts/render-code-email-preview.js <output.html>   English only, into that one file
const target = process.argv[2];
if (!target) {
  throw new Error("Usage: node scripts/render-code-email-preview.js <output-dir | output.html>");
}

// Fake values only. The redemption link is the app's fallback link, not a real code.
const SAMPLE = {
  code: "CMMFAKE7K4P9Q2MXYZ",
  expiresAt: "2027-03-15T08:00:00.000Z",
  autoRenews: false,
  redemptionUrl: null,
  unsubscribeUrl: "https://controlmymac.com/api/unsubscribe?token=preview-only",
};

function previewPage(locale) {
  const email = renderCodeEmail({ ...SAMPLE, locale });
  const emailBody = email.html.match(/<body[^>]*>([\s\S]*)<\/body>/)?.[1] || email.html;
  // The email's own <style> (small-screen rules) lives in its <head>; keep it.
  const emailStyles = (email.html.match(/<style[^>]*>[\s\S]*?<\/style>/g) || []).join("\n");
  return `<!doctype html>
<html lang="${locale}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Control My Mac email preview (${locale})</title>
<style>
*{box-sizing:border-box}body{margin:0;background:#eceff4;color:#17213a;font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif}.top{position:sticky;top:0;z-index:2;background:rgba(255,255,255,.94);backdrop-filter:blur(16px);border-bottom:1px solid #d9dee8;padding:18px 24px}.wrap{max-width:920px;margin:auto}.eyebrow{margin:0 0 6px;color:#5f6b84;font-size:12px;font-weight:700;letter-spacing:.06em;text-transform:uppercase}.subject{margin:0;font-size:22px;line-height:1.25}.meta{display:grid;grid-template-columns:52px 1fr;gap:5px 12px;margin-top:14px;color:#555f73;font-size:13px}.meta b{color:#293247}.notice{max-width:920px;margin:20px auto 0;padding:0 16px;color:#5f6b84;font-size:13px;text-align:center}.mail{padding-bottom:24px}.badge{display:inline-block;margin-left:8px;padding:3px 7px;border-radius:99px;background:#edf0f7;color:#5f6b84;font-size:11px;vertical-align:middle}details{max-width:560px;margin:0 auto 44px;padding:0 16px}summary{cursor:pointer;color:#3f4c6b;font-size:13px;font-weight:700}pre{white-space:pre-wrap;word-break:break-word;background:#fff;border:1px solid #d9dee8;border-radius:12px;padding:16px;font-size:13px;line-height:1.5}
</style>
${emailStyles}</head><body>
<header class="top"><div class="wrap"><p class="eyebrow">Transactional email preview · ${locale} <span class="badge">fake code</span></p><h1 class="subject">${escapeHtml(email.subject)}</h1><div class="meta"><b>From</b><span>Sebastian from Control My Mac &lt;configured Brevo sender&gt;</span><b>To</b><span>Your subscriber</span></div></div></header>
<p class="notice">Fake code and non-working unsubscribe link. Everything below is generated by the same template the backend sends.</p>
<main class="mail">${emailBody}</main>
<details><summary>Plain-text version</summary><pre>${escapeHtml(email.text)}</pre></details>
</body></html>`;
}

if (target.endsWith(".html")) {
  await writeFile(target, previewPage("en"), "utf8");
  console.log(target);
} else {
  await mkdir(target, { recursive: true });
  const locales = [...SUPPORTED_LOCALES];
  for (const locale of locales) {
    const file = join(target, `email-${locale}.html`);
    await writeFile(file, previewPage(locale), "utf8");
    console.log(file);
  }
  const links = locales
    .map((locale) => `<li><a href="email-${locale}.html">${locale}</a> · ${escapeHtml(renderCodeEmail({ ...SAMPLE, locale }).subject)}</li>`)
    .join("");
  await writeFile(
    join(target, "index.html"),
    `<!doctype html><html lang="en"><meta charset="utf-8"><title>Free-month email previews</title><body style="font:15px/1.7 -apple-system,sans-serif;margin:40px auto;max-width:640px;padding:0 16px"><h1>Free-month email, all languages</h1><ul>${links}</ul></body></html>`,
    "utf8",
  );
}
